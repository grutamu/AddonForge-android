#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
res=src-tauri/gen/android/app/src/main/res
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

npx tauri icon icon.svg --output "$tmp/full" >/dev/null
npx tauri icon src-tauri/icons/android/foreground.svg --output "$tmp/fg" >/dev/null
npx tauri icon src-tauri/icons/android/monochrome.svg --output "$tmp/mono" >/dev/null
cp icon.svg ui/icon.svg

for d in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
  mkdir -p "$res/mipmap-$d"
  cp "$tmp/full/android/mipmap-$d/ic_launcher.png" "$tmp/full/android/mipmap-$d/ic_launcher_round.png" "$res/mipmap-$d/"
  cp "$tmp/fg/android/mipmap-$d/ic_launcher_foreground.png" "$res/mipmap-$d/ic_launcher_foreground.png"
  cp "$tmp/mono/android/mipmap-$d/ic_launcher_foreground.png" "$res/mipmap-$d/ic_launcher_monochrome.png"
done

mkdir -p "$res/mipmap-anydpi-v26"
for name in ic_launcher ic_launcher_round; do
  cat > "$res/mipmap-anydpi-v26/$name.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-android-icons.sh -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/ic_launcher_background"/>
  <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
  <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
EOF
done
cat > "$res/values/ic_launcher_background.xml" <<'EOF'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-android-icons.sh -->
<resources>
  <color name="ic_launcher_background">#18202C</color>
</resources>
EOF
echo "Android icons written to $res"
